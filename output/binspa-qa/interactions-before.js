async page => {
  const checks=[];
  const check=(name,passed,detail)=>checks.push({name,passed,detail});
  await page.goto('https://127.0.0.1:5000/services/3',{waitUntil:'domcontentloaded'});
  await page.locator('.service-detail-name').waitFor();
  await page.locator('[data-list]').filter({hasText:'Đang tải...'}).waitFor({state:'hidden',timeout:15000}).catch(()=>{});
  check('reviews_loaded',!(await page.locator('[data-list]').innerText()).includes('Đang tải'),await page.locator('[data-list]').innerText());
  await page.screenshot({path:'output/binspa-qa/detail-390-settled-before.png',fullPage:true});
  await page.getByRole('button',{name:'Liên hệ',exact:true}).click();
  check('contact_opens_chat',await page.locator('#chatBox').evaluate(e=>e.classList.contains('show')),await page.locator('#chatBox').getAttribute('class'));
  await page.goto('https://127.0.0.1:5000/services',{waitUntil:'domcontentloaded'});
  await page.locator('.service-card').first().waitFor();
  const count=await page.locator('.service-card').count();
  await page.getByRole('button',{name:'Massage',exact:true}).click();
  check('category_filter',await page.locator('.service-card').count()>0 && await page.locator('.service-card').count()<count,await page.locator('.service-card').count());
  await page.getByRole('button',{name:'Tất cả',exact:true}).click();
  await page.locator('#searchInput').fill('zzzz-no-result');await page.locator('#searchInput').press('a');
  check('search_empty_state',await page.locator('#noResults').isVisible());
  await page.locator('#searchInput').fill('');await page.locator('#searchInput').press('Backspace');
  await page.locator('#sortSelect').selectOption('price-asc');
  const prices=await page.locator('.service-price').allTextContents();
  const nums=prices.map(v=>Number(v.replace(/\D/g,'')));
  check('sort_price',nums.every((v,i)=>i===0||nums[i-1]<=v));
  await page.locator('#mobileMenuBtn').click();
  check('mobile_menu_open',await page.locator('#mobileMenuBtn').getAttribute('aria-expanded')==='true');
  await page.screenshot({path:'output/binspa-qa/mobile-menu-before.png'});
  await page.keyboard.press('Escape');
  check('mobile_menu_escape',await page.locator('#mobileMenuBtn').getAttribute('aria-expanded')==='false');
  await page.locator('#userBtn').click();
  check('user_menu',await page.locator('#userDropdown').evaluate(e=>e.classList.contains('show')));
  await page.locator('#userDropdown a[href="/auth/login"]').click();
  await page.locator('#loginForm').waitFor();
  await page.locator('.toggle-password').click();
  check('show_password',await page.locator('#matkhau').getAttribute('type')==='text');
  await page.locator('.toggle-password').click();
  check('hide_password',await page.locator('#matkhau').getAttribute('type')==='password');
  await page.locator('#loginForm button[type=submit]').click();
  check('empty_login_validation',await page.locator('#taikhoan').evaluate(e=>e.validity.valueMissing));
  return checks;
}
