async page => {
  const base='http://127.0.0.1:5078';
  const errors=[],requests=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().startsWith(base+'/api/'))requests.push({path:r.url().replace(base,''),method:r.method()});});
  await page.goto(base+'/__preview/session?customer=1');
  await page.locator('#appointmentsList .ant-table').waitFor();
  requests.length=0;
  await page.goto(base+'/profile#treatments');
  await page.locator('#myTreatments .package-empty').waitFor();
  if(requests.some(r=>/my-appointments|payment\/invoices|reviews\/my/.test(r.path)))throw new Error('Inactive profile tab loaded: '+JSON.stringify(requests));
  checks.push('Only the active treatment tab loads data');
  await page.locator('.menu-link[data-section=info]').click();
  await page.locator('.menu-link[data-section=invoices]').click();
  await page.locator('#invoicesList .ant-table').waitFor();
  await page.goBack();
  if(!await page.locator('#info-section').evaluate(el=>el.classList.contains('active')))throw new Error('Back lost profile tab');
  await page.goForward();
  await page.locator('#invoicesList .ant-table').waitFor();
  checks.push('Profile Back/Forward');
  const cancelled=page.locator('#invoicesList tr').filter({hasText:'Đã hủy'});
  if(await cancelled.getByRole('button',{name:'Tiếp tục thanh toán'}).count())throw new Error('Cancelled invoice exposed payment');
  await page.locator('#invoicesList').getByRole('button',{name:'Chi tiết',exact:true}).first().click();
  await page.locator('.ant-drawer-body').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.ant-drawer-content-wrapper').waitFor({state:'hidden'});
  checks.push('Invoice detail and ESC');
  await page.locator('.menu-link[data-section=info]').click();
  await page.locator('[data-goto-section=edit]').click();
  await page.getByLabel('Họ và tên',{exact:true}).fill('Khách kiểm thử giao diện');
  requests.length=0;
  await page.getByRole('button',{name:'Lưu thay đổi',exact:true}).click();
  await page.getByText('Đã lưu thông tin của bạn.',{exact:true}).waitFor();
  if(requests.filter(r=>r.path==='/api/profile/update').length!==1)throw new Error('Profile save duplicated');
  checks.push('Profile form uses backend success');
  await page.locator('.menu-link[data-section=info]').click();
  await page.locator('[data-goto-section=password]').click();
  await page.getByLabel('Mật khẩu hiện tại',{exact:true}).fill('wrong-password');
  await page.getByLabel('Mật khẩu mới',{exact:true}).fill('new-test-password');
  await page.getByLabel('Nhập lại mật khẩu mới',{exact:true}).fill('new-test-password');
  requests.length=0;
  await page.getByRole('button',{name:'Đổi mật khẩu',exact:true}).click();
  await page.getByText('Mật khẩu hiện tại không chính xác',{exact:true}).waitFor();
  if(requests.some(r=>r.path==='/api/auth/restore-session'))throw new Error('Business 401 replayed password change');
  checks.push('Wrong password remains a form error');
  for(const width of [360,390,768,1024,1440]){
    await page.setViewportSize({width,height:960});
    await page.locator('.menu-link[data-section=appointments]').click();
    await page.locator('#appointmentsList .ant-app').waitFor();
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    if(overflow)throw new Error('Profile overflow '+width);
    if([390,1440].includes(width))await page.screenshot({path:`.test-tmp/customer-ui/account-${width}.png`});
  }
  await page.locator('#appointmentsList').getByRole('button',{name:'Đánh giá',exact:true}).first().click();
  await page.locator('dialog[open]').waitFor();
  await page.keyboard.press('Escape');
  checks.push('Completed appointment review context');
  if(errors.length)throw new Error(JSON.stringify(errors));
  return {checks,responsive:[360,390,768,1024,1440],errors};
}
