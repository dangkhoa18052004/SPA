async page => {
  const base='http://127.0.0.1:5079';const checks=[],errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:390,height:960});
  await page.goto(base+'/__preview/session');
  await page.evaluate(()=>{window.CustomerAuth.clearLocalSession();localStorage.setItem('spa_music_enabled','true');});
  await page.goto(base+'/');
  await page.locator('#servicesGrid article').first().waitFor();
  await page.keyboard.press('Tab');
  if(!await page.locator('.skip-link').evaluate(el=>el===document.activeElement))throw new Error('Skip link is not first in keyboard order');
  await page.keyboard.press('Enter');
  if(!await page.locator('#customer-content').evaluate(el=>el===document.activeElement))throw new Error('Skip link did not move focus');
  await page.locator('#mobileMenuBtn').focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('#navMenu a')===document.activeElement);
  if(!await page.locator('#navMenu a').first().evaluate(el=>el===document.activeElement))throw new Error('Keyboard menu did not move focus');
  await page.keyboard.press('Escape');
  if(!await page.locator('#mobileMenuBtn').evaluate(el=>el===document.activeElement))throw new Error('Menu did not restore focus');
  if(!await page.locator('#spaAudio').evaluate(audio=>audio.paused))throw new Error('Music autoplayed');
  checks.push('Keyboard skip/menu/ESC focus; no music autoplay');
  const nav=await page.locator('.mobile-bottom-nav').boundingBox(),chat=await page.locator('#chatFloat').boundingBox();
  if(!nav||!chat||chat.y<nav.y)throw new Error('Chat floats over page actions on mobile');
  await page.locator('#chatFloat').click();
  await page.locator('#chatBox.show').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('#chatBox.show').waitFor({state:'hidden'});
  checks.push('Chat occupies mobile navigation and closes with ESC');
  await page.screenshot({path:'.test-tmp/customer-ui/final-390-home.png'});
  await page.route('**/api/services',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,services:[{madv:1,tendv:'<img src=x onerror="window.__attack=true"> Tên dịch vụ rất dài cần xuống dòng',mota:'<script>window.__attack=true</script>',gia:null,thoiluong:45,anhdichvu:'broken-image'}]})}));
  await page.goto(base+'/services');await page.locator('#servicesGrid article').waitFor();
  await page.locator('#servicesGrid img').evaluate(img=>new Promise(resolve=>{if(img.complete&&img.src.endsWith('default-service.jpg'))return resolve(true);img.addEventListener('load',()=>resolve(true),{once:true});}));
  if(await page.evaluate(()=>!!window.__attack))throw new Error('API text executed as HTML');
  if(!await page.locator('.service-price').filter({hasText:'Liên hệ'}).count())throw new Error('Missing price became zero');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Long title overflow');
  await page.unroute('**/api/services');
  checks.push('Image failure, long title, null price and escaped API text');
  await page.route('**/api/services',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,services:[]})}));
  await page.reload();await page.locator('#noResults').waitFor({state:'visible'});await page.unroute('**/api/services');
  await page.route('**/api/services',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({success:false})}));
  await page.reload();await page.locator('#servicesGrid [role=alert]').waitFor();await page.unroute('**/api/services');
  await page.locator('#servicesGrid').getByRole('button',{name:'Thử lại'}).click();await page.locator('#servicesGrid article').first().waitFor();
  checks.push('Empty, error and retry');
  await page.setViewportSize({width:1440,height:960});
  await page.goto(base+'/services');
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Text resize overflow');
  await page.screenshot({path:'.test-tmp/customer-ui/text-resize-200.png'});
  checks.push('200% root text resize (not native browser zoom)');
  await page.goto(base+'/__preview/session?customer=1');
  await page.goto(base+'/profile#invoices');await page.locator('#invoicesList .ant-table').waitFor();
  const detail=page.locator('#invoicesList').getByRole('button',{name:'Chi tiết',exact:true}).first();
  await detail.click();await page.locator('.ant-drawer-body').waitFor();await page.keyboard.press('Escape');
  await page.locator('.ant-drawer-content-wrapper').waitFor({state:'hidden'});
  if(!await detail.evaluate(el=>el===document.activeElement))throw new Error('Drawer did not restore trigger focus');
  await page.screenshot({path:'.test-tmp/customer-ui/final-1440-profile.png'});
  if(errors.length)throw new Error(JSON.stringify(errors));
  return {checks,drawerFocusRestored:true,errors};
}
